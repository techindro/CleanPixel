  /// Initialize and load saved language
  static Future<void> init() async {
    final prefs = await SharedPreferences.getInstance();
    final savedCode = prefs.getString(_prefKey) ?? 'en';
    currentLocale.value = savedCode;
  }

  /// Change active language and persist
  static Future<void> setLanguage(String code) async {
    final prefs = await SharedPreferences.getInstance();
    await prefs.setString(_prefKey, code);
    currentLocale.value = code;
  }

  /// Translate a key with fallback to English
  static String tr(String key) {
    final lang = currentLocale.value;
    final dict = _translations[lang] ?? _translations['en']!;
    return dict[key] ?? _translations['en']![key] ?? key;
  }

  /// Get current LanguageModel object
  static LanguageModel getCurrentLanguage() {
    final code = currentLocale.value;
    return supportedLanguages.firstWhere(
      (e) => e.code == code,
      orElse: () => supportedLanguages.first,
    );
  }
